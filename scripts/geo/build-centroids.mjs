// Build public/geo/buildings/centroids.bin from the per-municipality GeoJSONSeq
// files in tmp/buildings/geojsonl. Each building becomes a fixed 13-byte record:
//
//   offset 0  Float32  lat
//   offset 4  Float32  lng
//   offset 8  Uint16   numberOfDwellings (clamped 0..65535)
//   offset 10 Uint16   construction year (0 = unknown)
//   offset 12 Uint8    use code (see USE_CODES)
//
// The file is prefixed with an 8-byte header: ASCII "MCFB" + Uint32 record count.
// The browser loads it once and computes catchment-ring aggregates client-side
// (dwellings, % pre-1980, residential share). No database, no API.
//
// Regenerated by build-comunidad-buildings.ps1 after tiling; can also be run
// standalone:  node scripts/geo/build-centroids.mjs
import { readFileSync, writeFileSync, readdirSync, createReadStream } from 'node:fs';
import { createInterface } from 'node:readline';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const GEO_DIR = join(REPO, 'tmp', 'buildings', 'geojsonl');
const OUT = join(REPO, 'public', 'geo', 'buildings', 'centroids.bin');

const USE_CODES = {
  '1_residential': 1, '2_agriculture': 2, '3_industrial': 3,
  '4_1_office': 4, '4_2_retail': 5, '4_3_publicServices': 6,
};

function parseYear(beginning) {
  // e.g. "1965-01-01T00:00:00"; reject garbage / unpopulated ("--01-01...").
  const m = String(beginning || '').match(/^(\d{1,4})-/);
  if (!m) return 0;
  const y = parseInt(m[1], 10);
  return (y >= 1700 && y <= 2026) ? y : 0;
}

// Average every coordinate in a (Multi)Polygon for a cheap centroid. Building
// footprints are tiny relative to a 300m+ ring, so vertex-average is plenty.
function centroid(geom) {
  let sx = 0, sy = 0, n = 0;
  const walk = (a) => {
    if (typeof a[0] === 'number') { sx += a[0]; sy += a[1]; n++; return; }
    for (const c of a) walk(c);
  };
  if (geom && geom.coordinates) walk(geom.coordinates);
  return n ? [sx / n, sy / n] : null;
}

async function main() {
  const files = readdirSync(GEO_DIR).filter(f => f.endsWith('.geojsonl'));
  if (files.length === 0) {
    console.error(`No .geojsonl files in ${GEO_DIR}. Run build-comunidad-buildings.ps1 first.`);
    process.exit(1);
  }

  const REC = 13;
  let cap = 1 << 20;
  let buf = Buffer.allocUnsafe(cap * REC);
  let count = 0;

  const ensure = () => {
    if (count >= cap) {
      cap *= 2;
      const nb = Buffer.allocUnsafe(cap * REC);
      buf.copy(nb, 0, 0, count * REC);
      buf = nb;
    }
  };

  for (const f of files) {
    const rl = createInterface({ input: createReadStream(join(GEO_DIR, f)), crlfDelay: Infinity });
    for await (const line of rl) {
      if (!line.trim()) continue;
      let feat;
      try { feat = JSON.parse(line); } catch { continue; }
      const c = centroid(feat.geometry);
      if (!c) continue;
      const p = feat.properties || {};
      const dw = Math.max(0, Math.min(65535, Math.round(Number(p.numberOfDwellings) || 0)));
      const yr = parseYear(p.beginning);
      const use = USE_CODES[p.currentUse] || 0;
      ensure();
      const off = count * REC;
      buf.writeFloatLE(c[1], off);      // lat
      buf.writeFloatLE(c[0], off + 4);  // lng
      buf.writeUInt16LE(dw, off + 8);
      buf.writeUInt16LE(yr, off + 10);
      buf.writeUInt8(use, off + 12);
      count++;
    }
    console.log(`  ${f}: total ${count}`);
  }

  const header = Buffer.alloc(8);
  header.write('MCFB', 0, 'ascii');
  header.writeUInt32LE(count, 4);
  writeFileSync(OUT, Buffer.concat([header, buf.subarray(0, count * REC)]));
  const mb = (8 + count * REC) / 1e6;
  console.log(`\nOK  ${OUT}  ${count} buildings, ${mb.toFixed(1)} MB`);
}

main().catch(e => { console.error(e); process.exit(1); });
